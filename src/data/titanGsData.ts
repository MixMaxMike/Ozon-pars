export function normalizeOzonPhotoUrl(url: string): string {
  if (!url) return '';
  let cleaned = url.replace(/c.cdn.ozon.ru/g, 'ir.ozone.ru');
  if (!cleaned.includes('/wc1200/') && /\/s3\/multimedia-[a-z0-9]+\//.test(cleaned)) {
    cleaned = cleaned.replace(/\/s3\/multimedia-([a-z0-9]+)\/(\d+\.jpg)/, '/s3/multimedia-$1/wc1200/$2');
  }
  return cleaned;
}

